/** Нижний регистр, ё→е, любые пробельные символы (включая переносы строк) — один пробел. */
export function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

const KAZAKH_LETTERS = /[әғқңөұүһі]/i;

export function detectLanguage(text: string): Language {
  return KAZAKH_LETTERS.test(text) ? "kk" : "ru";
}

/**
 * Предупреждение о мошенниках (памятка банка, сообщение в чате), а не сама попытка:
 * в таких текстах слова мошенника приводятся как цитата. Контекст определяется по словам,
 * которые разоблачают цитату («уловка», «не верьте», «алдау»), а не по слову «памятка».
 */
const WARNING_CONTEXT =
  /(?<!не )уловк|это (?:обман|развод)|не верьте|не ведитесь|не заполняйте|пожалуйтесь|фальшив|лжесотрудник|участились|мне (?:звонил|звонили|пишут|написали)|мошенники (?:пишут|звонят|рассылают)|положила? трубку|(?<!\p{L})алдау(?!\p{L})|сенбеңіз|деуі мүмкін|мәжбүрлеп жүр|жалған қоңырау|тұтқаны қойдым|алаяқтар .{0,20}жазып/u;

const QUOTED = /«[^»]{0,300}»|"[^"]{0,300}"|“[^”]{0,300}”/g;

/**
 * Однозначный признак (просьба кода, «безопасный счёт», удалённый доступ…) засчитывается
 * ВСЕГДА — как бы ни была построена фраза. Попытки отличить предупреждение банка
 * («банк никогда не просит код») от уловки («не спрашивайте зачем и назовите код»)
 * регулярными выражениями обходятся подбором слов (3 цикла ревью это показали), поэтому
 * правила работают «на отказ»: пропущенная схема стоит клиенту сбережений, ложная тревога —
 * паузы. Различать такие тексты по смыслу — задача LLM-слоя (подключается ключом).
 * Шаблоны проверяются по всему тексту, поэтому требование в соседнем предложении не теряется.
 */
function strongFires(sig: Signal, text: string): boolean {
  return sig.patterns.some((p) => p.test(text));
}

export function evaluateRules(text: string): RuleResult {
  const full = normalize(text);
  const isWarning = WARNING_CONTEXT.test(full);
  // Слабые признаки в предупреждении не считаются по цитатам — это слова мошенника, а не просьба
  const weakText = isWarning ? full.replace(QUOTED, " ") : full;

  const fired = SIGNALS.filter((sig) =>
    sig.strong ? strongFires(sig, full) : sig.patterns.some((p) => p.test(weakText)),
  );
  const links = suspiciousLinks(weakText);
  const strong = fired.some((s) => s.strong) || links.length > 0;

  // Защитные признаки действуют, только когда нет однозначного требования: приписка
  // «никому не сообщайте код» рядом с «назовите код» риск не снижает.
  const counted = strong ? fired.filter((s) => s.weight > 0) : fired;

  let score = counted.reduce((sum, s) => sum + s.weight, 0);
  const reasons = counted.filter((s) => s.weight > 0).map((s) => s.reason);
  const ids = counted.map((s) => s.id);

  if (links.length > 0) {
    score += 55;
    ids.push("suspicious_link");
    reasons.push("Ссылка ведёт на сайт, который не принадлежит банку или госоргану");
  }
  // Номер телефона в SMS «от банка» с угрозой — типичный приём
  if (PHONE_IN_TEXT.test(full) && ids.includes("threat") && !ids.includes("callback_number")) score += 10;
  // Предупреждение без собственных однозначных требований — не атака
  if (isWarning && !strong) {
    score -= 40;
    ids.push("warning_context");
  }

  score = Math.max(0, Math.min(100, score));
  const scamType = score >= 40 ? (TYPE_PRIORITY.find((p) => p.signals.some((id) => ids.includes(id)))?.type ?? null) : null;

  return { score, scamType, reasons: score >= 40 ? reasons : [], signals: ids, strong };
}
