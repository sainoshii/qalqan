/**
 * Движок правил: прозрачные признаки социальной инженерии для русского и казахского.
 * Работает без сети и без LLM — это и основной детектор, и фолбэк.
 *
 * Каждое правило — признак с весом и объяснением для клиента. Итоговый скор —
 * сумма весов сработавших признаков (0–100). Защитные признаки («никому не
 * сообщайте код», «позвоните по номеру на обороте карты») снижают скор: так
 * настоящие уведомления банка не принимаются за мошенничество.
 *
 * Шаблоны сравниваются с канонической формой текста (`normalize.ts`): латиница и смешанная
 * раскладка уже приведены к кириллице. Русские шаблоны пишутся как есть. Казахские — в обычной
 * орфографии и оборачиваются в `kk(...)`: так они совпадают и с «упрощёнными» буквами
 * («кауипсиз шот»), и с латиницей («qauipsiz shot»). Латинских литералов в шаблонах нет, кроме
 * слов, которые нормализация оставляет как есть (sms, cvv, cvc, anydesk…, http).
 *
 * Правила настраивались только по части `dev` тестового набора (data/README.md).
 */

export interface Signal {
  id: string;
  weight: number; // > 0 — признак мошенничества, < 0 — защитный признак
  reason: string; // объяснение для клиента (пусто у защитных)
  type?: ScamType; // какой схеме соответствует признак
  strong?: boolean; // однозначный признак: LLM не может опустить итог ниже «высокого»
  patterns: RegExp[];
}

/** Домены, которые считаются официальными (ссылки на них не подозрительны). */
const TRUSTED_DOMAINS = ["bcc.kz", "egov.kz", "gov.kz", "nationalbank.kz", "kaspi.kz", "kazpost.kz", "halykbank.kz"];

export const SUSPICIOUS_LINK_REASON = "Ссылка ведёт на сайт, который не принадлежит банку или госоргану";

export const URL_PATTERN = /(?:https?:\/\/)?(?:[a-z0-9-]+\.)+[a-z]{2,}(?:\/[^\s]*)?/gi;

export function isTrustedLink(link: string): boolean {
  const host = link.replace(/^https?:\/\//i, "").split("/")[0].toLowerCase();
  return TRUSTED_DOMAINS.some((d) => host === d || host.endsWith(`.${d}`));
}

/**
 * Ссылки на сайты не из списка официальных. Границы ссылок ищет `linkSpans` — то же, что
 * находит `URL_PATTERN`, но за линейное время (выражение на длинной строке без пробелов
 * перебирает начала квадратично; совпадение проверяется в tests/normalize.test.ts).
 */
export function suspiciousLinks(text: string): string[] {
  const low = text.toLowerCase();
  return linkSpans(low)
    .map(([from, to]) => low.slice(from, to))
    .filter((link) => !isTrustedLink(link));
}

const PHONE_IN_TEXT = /(?:\+\s?7|(?<!\d)8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/;

/** Основы казахских глаголов передачи: «айт» (сказать), «жібер» (отправить), «жаз» (написать), «оқы» (прочитать), «хабарла» (сообщить).
 * «бер» (дать) не входит: на dev ничего не добавляет, а в памятках («кодты беріңіз дегенге сенбеңіз») даёт strong. */
const KK_DEMAND_STEMS = ["айт", "жібер", "жаз", "оқы", "хабарла"];

/**
 * Просьба передать секрет — композиционно: любое слово-секрет и любой повелительный глагол
 * передачи (RU/KZ), в любом порядке, в пределах одной фразы. Отрицательные формы
 * («не сообщайте», «айтпаңыз») сюда не попадают: в списке только повелительные формы.
 */
const SECRET_WORDS = [
  // Формы слова «код» перечислены (RU и KZ), с границей слова в SECRET_DEMAND: «код + любые буквы»
  // ловило «кодекс», «кодек», «кодер», «кодталған» (ревью, циклы 2–3)
  String.raw`код(?:а|у|ом|е|ов|ам|ами|ах)?`,
  kkSource(String.raw`код(?:ы|ты|ын|ың|ыңды|ыңыз|ыңызды|ыңызға|ым|ымды|тар|тарды|тарын|тарыңыз|тарыңызды|қа|пен|тан)`),
  String.raw`cvv\d?|cvc\d?|пин(?:-?код)?|парол\p{L}*`,
  kkSource(String.raw`құпиясөз\p{L}*`),
  String.raw`три цифры|шесть цифр|цифр\p{L}* из sms`,
  // «санд[ы]» — без допуска ы/і: «санди» в упрощённой записи — это «сәнді» (модный), а не «санды» (цифру)
  kkSource(String.raw`сандар(?:ды)?|санд[ы]|цифрлар\p{L}*|цифрды|үш цифр\p{L}*`),
].join("|");
const DEMAND_VERBS = [
  String.raw`назови(?:те)?|продиктуй(?:те)?|скажи(?:те)?|сообщи(?:те)?|отправь(?:те)?|пришли(?:те)?|перешли(?:те)?|напиши(?:те)?|прочти(?:те)?|прочитай(?:те)?`,
  // Казахские глаголы передачи — все формы просьбы и требования (см. demandForms), без отрицаний
  ...KK_DEMAND_STEMS.map((stem) => kkSource(demandForms(stem))),
].join("|");
const SECRET_DEMAND = [
  new RegExp(String.raw`(?<!\p{L})(?:${DEMAND_VERBS})(?!\p{L})[^.!?]{0,60}(?<!\p{L})(?:${SECRET_WORDS})(?!\p{L})`, "u"),
  new RegExp(String.raw`(?<!\p{L})(?:${SECRET_WORDS})(?!\p{L})[^.!?]{0,60}(?<!\p{L})(?:${DEMAND_VERBS})(?!\p{L})`, "u"),
];

