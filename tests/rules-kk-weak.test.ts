import { describe, expect, it } from "vitest";
import { analyzeMessage } from "@/lib/detector";
import { evaluateRules } from "@/lib/detector/rules";

/**
 * Слабый казахский признак обещания дохода (income_promise, 19 ноября). Сам вмешательства не даёт
 * (вес 25), но подтверждает
 * статистическую модель по правилу двух сигналов. Все сообщения синтетические, написаны для теста.
 */
const fires = (text: string) => evaluateRules(text).signals;

// Цикл 4 (решение лида): шаблоны transfer_demand, secrecy и upfront_fee на казахском убраны —
// за 3 цикла ревью давали ложные вмешательства; «N мың салшы» убран после цикла kk-weak-narrow. Остался income_promise.

describe("обещание дохода (income_promise)", () => {
  it.each([
    "Салым қауіпсіз, минус болмайды.",
    "Ай сайын кепілді 15% түседі.",
    "Риск жоқ, бәрі гарант.",
    "20 мың сал, ертең 40 мың аласың.",
    "Aqshany eki ese kobeitemiz.",
  ])("%s", (text) => {
    const result = evaluateRules(text);
    expect(result.signals).toContain("income_promise");
    expect(result.strong).toBe(false); // слабый признак: однозначным не становится
  });

  it("«гарантия» по-русски — не обещание дохода", () => {
    expect(fires("Гарантия на ремонт — 12 месяцев.")).not.toContain("income_promise");
  });
});

describe("слабые признаки сами не дают вмешательства", () => {
  it.each([
    "Апа, түскі асқа 5000 жіберші, әмиянымды үйде ұмытып кетіппін.",
    "Асельге сыйлыққа ақша жинап жатырмыз, менің картама аудар.",
    "Бөлімшеге бармаңыз, кезек ұзақ, қосымшадан жасауға болады.",
  ])("%s", (text) => {
    const result = evaluateRules(text);
    expect(result.strong).toBe(false);
    expect(result.score).toBeLessThan(40); // ниже даже предупреждения
  });
});

